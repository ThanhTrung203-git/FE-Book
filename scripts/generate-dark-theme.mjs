import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import { darkDeclaration } from "./theme-colors.mjs";

const directory=new URL("../src/",import.meta.url);
const excluded=new Set(["theme.css","darkPalette.css"]);
const all=(await readdir(directory)).filter(name=>name.endsWith(".css")&&!excluded.has(name));
const sources=[...new Set(["styles.css","ui.css","catalog.css",...all.sort()])];
const prefix='html[data-theme="dark"]';
function scope(selector){
  if(selector.startsWith(":root"))return selector.replace(/^:root/,prefix);
  if(/^html(?=$|[\s.:#\[])/.test(selector))return selector.replace(/^html/,prefix);
  return prefix+" "+selector;
}
function transform(node){
  if(node.type==="rule"){
    const result=postcss.rule({selector:node.selectors.map(scope).join(",\n")});
    for(const declaration of node.nodes||[]){
      if(declaration.type!=="decl")continue;
      const value=darkDeclaration(declaration.prop,declaration.value);
      if(value!==declaration.value)result.append(declaration.clone({value}));
    }
    return result.nodes?.length?result:null;
  }
  if(node.type==="atrule"&&["media","supports","layer","container"].includes(node.name)){
    const result=postcss.atRule({name:node.name,params:node.params});
    for(const child of node.nodes||[]){const changed=transform(child);if(changed)result.append(changed);}
    return result.nodes?.length?result:null;
  }
  return null;
}
const output=postcss.root();
output.append(postcss.comment({text:"Generated by npm run theme:generate. Edit source styles or scripts/theme-colors.mjs, then regenerate."}));
for(const source of sources){
  const root=postcss.parse(await readFile(new URL(source,directory),"utf8"),{from:source});
  output.append(postcss.comment({text:source}));
  for(const node of root.nodes){const changed=transform(node);if(changed)output.append(changed);}
}
await writeFile(new URL("darkPalette.css",directory),output.toString()+"\n","utf8");
console.log("Generated dark palette for "+sources.length+" stylesheets.");
