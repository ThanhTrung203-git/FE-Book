const reverseDictionary = Object.fromEntries(Object.entries(dictionary).map(([vi, en]) => [en, vi]));

export function translate(text, language, parameters = {}) {
  if (text && typeof text === "object" && typeof text.key === "string") return translate(text.key, language, text.params);
  if (typeof text !== "string") return text;
  let source = shipmentStatuses[text] || reverseDictionary[text] || text;
  let values = parameters;
  if (source.startsWith("Đặt hàng thành công: ") && source !== "Đặt hàng thành công: {code}") {
    values = { code: source.slice("Đặt hàng thành công: ".length) };
    source = "Đặt hàng thành công: {code}";
  }
  const profileMatch = /^Đã cập nhật hồ sơ khách hàng #(\d+)\.$/.exec(source);
  if (profileMatch) { values = { id: profileMatch[1] }; source = "Đã cập nhật hồ sơ khách hàng #{id}."; }
  const translated = language === "en" ? dictionary[source] || source : source;
  return translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => { try { return localStorage.getItem("book-language") === "en" ? "en" : "vi"; } catch { return "vi"; } });
  useEffect(()=>{const sync=event=>{if(event.key==="book-language"||event.key===null){try{setLanguage(localStorage.getItem("book-language")==="en"?"en":"vi");}catch{}}};window.addEventListener("storage",sync);return()=>window.removeEventListener("storage",sync);},[]);
  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === "vi" ? "Mộc — Nhà sách" : "Mộc — Bookstore";
  }, [language]);
  const changeLanguage = (next) => {
    if(!["vi","en"].includes(next))return;
    try { localStorage.setItem("book-language", next); } catch {}
    setLanguage(next);
    document.documentElement.lang = next;
  };
  const value = useMemo(() => ({
    language,
    setLanguage: changeLanguage,
    t: (text, parameters) => translate(text, language, parameters),
    categoryLabel: (name) => localizeCategory(name, language),
    money: (value) => new Intl.NumberFormat(language === "en" ? "en-US" : "vi-VN", {
      style: "currency", currency: "VND", maximumFractionDigits: 0,
    }).format(Number(value || 0)),
    dateTime: (value) => value ? new Date(value).toLocaleString(language === "en" ? "en-GB" : "vi-VN") : "—",
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

